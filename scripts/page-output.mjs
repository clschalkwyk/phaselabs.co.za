import { legacyRoutes, siteOrigin } from '../src/pages.js';

export function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character]);
}

export function pageHead(page) {
  const canonical = `${siteOrigin}${page.path}`;
  return [
    `<title>${escapeHtml(page.title)}</title>`,
    `<meta name="description" content="${escapeHtml(page.description)}" />`,
    '<meta property="og:type" content="website" />',
    `<meta property="og:title" content="${escapeHtml(page.ogTitle || page.title)}" />`,
    `<meta property="og:description" content="${escapeHtml(page.ogDescription || page.description)}" />`,
    `<meta property="og:url" content="${escapeHtml(canonical)}" />`,
    `<link rel="canonical" href="${escapeHtml(canonical)}" />`,
  ].join('\n    ');
}

// Runs before the application bundle. It is deliberately a browser redirect,
// not an HTTP redirect: query-aware 301s require verified CloudFront setup.
export function legacyBrowserScript() {
  return `<script>\n(function () {\n  var url = new URL(window.location.href);\n  if (url.pathname !== '/' && url.pathname !== '/index.html') return;\n  var routes = ${JSON.stringify(legacyRoutes)};\n  var route = routes.find(function (item) { return url.searchParams.get(item.key) === item.value; });\n  if (!route) return;\n  routes.forEach(function (item) { url.searchParams.delete(item.key); });\n  var query = url.searchParams.toString();\n  window.location.replace(route.path + (query ? '?' + query : '') + url.hash);\n})();\n</script>`;
}

// Optional viewer-request CloudFront Function. Generated from the same registry,
// but never installed by the site build or the deployment workflow.
export function cloudFrontRedirectFunction() {
  return `// Generated by npm run build. Review existing edge associations before installation.
function handler(event) {
  var request = event.request;
  if (request.method !== 'GET' && request.method !== 'HEAD') return request;
  if (request.uri !== '/' && request.uri !== '/index.html') return request;
  var routes = ${JSON.stringify(legacyRoutes)};
  var query = request.querystring || {};
  var target;
  function decode(value) { try { return decodeURIComponent(value.replace(/\\+/g, ' ')); } catch (error) { return value; } }
  function encode(value) { return encodeURIComponent(decode(value)); }
  for (var i = 0; i < routes.length; i++) {
    var item = query[routes[i].key];
    if (item && decode(item.value) === routes[i].value) { target = routes[i].path; break; }
  }
  if (!target) return request;
  var remaining = [];
  Object.keys(query).forEach(function (key) {
    if (routes.some(function (route) { return route.key === key; })) return;
    var values = query[key].multiValue || [query[key]];
    values.forEach(function (item) { remaining.push(encode(key) + '=' + encode(item.value)); });
  });
  return {
    statusCode: 301,
    statusDescription: 'Moved Permanently',
    headers: {
      location: { value: target + (remaining.length ? '?' + remaining.join('&') : '') },
      'cache-control': { value: 'public, max-age=300' }
    }
  };
}
`;
}
